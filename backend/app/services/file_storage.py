import hashlib
from pathlib import Path
from uuid import uuid4

from fastapi import HTTPException, UploadFile, status

from app.config import Settings

ALLOWED_EXTENSIONS = {".pdf", ".txt", ".docx", ".json", ".csv"}
EXPECTED_MEDIA_TYPES = {
    ".pdf": {"application/pdf", "application/octet-stream"},
    ".txt": {"text/plain", "application/octet-stream"},
    ".docx": {
        "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
        "application/octet-stream",
    },
    ".json": {"application/json", "text/json", "application/octet-stream"},
    ".csv": {"text/csv", "application/csv", "application/vnd.ms-excel", "application/octet-stream"},
}
CHUNK_SIZE = 1024 * 1024


async def store_upload(upload: UploadFile, settings: Settings) -> tuple[str, int, str, str]:
    filename = Path(upload.filename or "upload").name
    extension = Path(filename).suffix.lower()
    if extension not in ALLOWED_EXTENSIONS:
        raise HTTPException(status_code=415, detail="Unsupported file type.")
    if not upload.content_type or len(upload.content_type) > 200:
        raise HTTPException(status_code=415, detail="A valid media type is required.")
    media_type = upload.content_type.split(";", 1)[0].strip().lower()
    if media_type not in EXPECTED_MEDIA_TYPES[extension]:
        raise HTTPException(status_code=415, detail="The file extension and media type do not match.")

    storage_key = uuid4().hex
    folder = Path(settings.file_storage_root).resolve()
    folder.mkdir(parents=True, exist_ok=True)
    destination = folder / storage_key
    digest = hashlib.sha256()
    size = 0
    try:
        with destination.open("xb") as target:
            while chunk := await upload.read(CHUNK_SIZE):
                size += len(chunk)
                if size > settings.max_upload_mb * 1024 * 1024:
                    raise HTTPException(status_code=413, detail="The uploaded file exceeds the size limit.")
                digest.update(chunk)
                target.write(chunk)
        if size == 0:
            raise HTTPException(status_code=422, detail="Empty files are not accepted.")
        return storage_key, size, digest.hexdigest(), extension
    except Exception:
        destination.unlink(missing_ok=True)
        raise
    finally:
        await upload.close()


def delete_stored_file(settings: Settings, storage_key: str) -> None:
    # storage_key is generated by this service and may not contain path separators.
    if Path(storage_key).name != storage_key:
        return
    (Path(settings.file_storage_root).resolve() / storage_key).unlink(missing_ok=True)
